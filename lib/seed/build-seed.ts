import type { AchievementDefinition } from "../achievements/catalog";
import { LEVELS, type Quiz } from "../types";

/**
 * Generates supabase/seed.sql from the JSON sources (data/quizzes, data/achievements.json).
 * The SQL is idempotent: run it again after editing the JSON and rows are updated in place.
 * Answer options keep their ids, questions missing from the JSON are deactivated (never
 * deleted, so history keeps working) and achievements missing from the catalog are disabled.
 */

const LEVEL_NAMES: Record<(typeof LEVELS)[number], string> = {
  basic: "Basic",
  intermediate: "Intermediate",
  advanced: "Advanced",
};

export function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function sqlNullable(value: string | undefined | null): string {
  return value == null ? "null" : sqlString(value);
}

function values(rows: string[][]): string {
  return rows.map((row) => `  (${row.join(", ")})`).join(",\n");
}

export function buildSeedSql(quizGroups: Quiz[][], achievements: AchievementDefinition[]): string {
  const quizzes = quizGroups.flat();
  const quizIds = [...new Set(quizzes.map((q) => q.id))];
  const out: string[] = [
    "-- Generated by `npm run db:seed:generate` from data/. Do not edit by hand.",
    "begin;",
    "",
    `insert into public.levels (id, position, name) values\n${values(
      LEVELS.map((level, index) => [sqlString(level), String(index + 1), sqlString(LEVEL_NAMES[level])]),
    )}\non conflict (id) do update set position = excluded.position, name = excluded.name;`,
  ];

  if (quizIds.length > 0) {
    out.push(
      `insert into public.quizzes (id, is_published) values\n${values(quizIds.map((id) => [sqlString(id), "true"]))}\non conflict (id) do update set is_published = true, updated_at = now();`,
      `update public.quizzes set is_published = false, updated_at = now() where id not in (${quizIds.map(sqlString).join(", ")});`,
      `insert into public.quiz_localizations (quiz_id, language, title) values\n${values(
        quizzes.map((q) => [sqlString(q.id), sqlString(q.language), sqlString(q.title)]),
      )}\non conflict (quiz_id, language) do update set title = excluded.title;`,
    );
  }

  for (const quiz of quizzes) {
    const key = `${sqlString(quiz.id)}, ${sqlString(quiz.language)}`;
    out.push(
      "",
      `-- ${quiz.id} (${quiz.language})`,
      `insert into public.questions (quiz_id, language, source_id, level_id, prompt, explanation, is_active) values\n${values(
        quiz.questions.map((q) => [
          key,
          String(q.id),
          sqlString(q.level),
          sqlString(q.question),
          sqlNullable(q.explanation),
          "true",
        ]),
      )}\non conflict (quiz_id, language, source_id) do update set level_id = excluded.level_id, prompt = excluded.prompt, explanation = excluded.explanation, is_active = true;`,
      `update public.questions set is_active = false where quiz_id = ${sqlString(quiz.id)} and language = ${sqlString(quiz.language)} and source_id not in (${quiz.questions.map((q) => q.id).join(", ")});`,
      `insert into public.answer_options (question_id, source_index, body, is_correct)
select q.id, v.source_index, v.body, v.source_index = 0
from (values\n${values(
        quiz.questions.flatMap((q) =>
          [q.correctAnswer, ...q.wrongAnswers].map((body, index) => [String(q.id), String(index), sqlString(body)]),
        ),
      )}\n) as v (source_id, source_index, body)
join public.questions q on q.quiz_id = ${sqlString(quiz.id)} and q.language = ${sqlString(quiz.language)} and q.source_id = v.source_id
on conflict (question_id, source_index) do update set body = excluded.body, is_correct = excluded.is_correct;`,
    );
  }

  if (achievements.length > 0) {
    out.push(
      "",
      "-- Achievements",
      `insert into public.achievements (slug, name, description, icon, category, rarity, criteria_type, criteria_config, sort_order, is_active) values\n${values(
        achievements.map((a, index) => [
          sqlString(a.slug),
          sqlString(a.name),
          sqlString(a.description),
          sqlString(a.icon),
          sqlString(a.category),
          sqlString(a.rarity),
          sqlString(a.criteria_type),
          `${sqlString(JSON.stringify(a.criteria_config))}::jsonb`,
          String((index + 1) * 10),
          String(a.is_active),
        ]),
      )}\non conflict (slug) do update set name = excluded.name, description = excluded.description, icon = excluded.icon, category = excluded.category, rarity = excluded.rarity, criteria_type = excluded.criteria_type, criteria_config = excluded.criteria_config, sort_order = excluded.sort_order, is_active = excluded.is_active, updated_at = now();`,
      `update public.achievements set is_active = false, updated_at = now() where slug not in (${achievements.map((a) => sqlString(a.slug)).join(", ")});`,
    );
  }

  out.push("", "commit;", "");
  return out.join("\n");
}
